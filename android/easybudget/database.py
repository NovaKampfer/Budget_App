# easybudget/database.py
#
# The **data layer** of the Android app. Everything that touches the SQLite
# database lives here, so the UI code never writes SQL directly.
#
# The database stores:
#   1. transactions      - every expense (negative) or income (positive)
#   2. recurring_rules   - "recipes" that generate transactions, e.g.
#                          "$25 every day" or "$1,200 every month"
#   3. settings          - small key/value preferences (currency, theme, ...)
#
# Money is always stored as integer **cents** so rounding errors can never
# corrupt a balance ($12.34 is stored as 1234).
#
# The transactions / recurring_rules tables use the same layout as the
# Windows version, plus one extra column (recurring_rules.end_date) that
# makes "delete this and future occurrences" possible.

import sqlite3
from datetime import date, timedelta

SCHEMA = """
CREATE TABLE IF NOT EXISTS transactions(
  id INTEGER PRIMARY KEY,
  date TEXT NOT NULL,               -- YYYY-MM-DD
  amount_cents INTEGER NOT NULL,    -- negative = expense, positive = income
  note TEXT DEFAULT '',
  rule_id INTEGER                   -- set when generated by a recurring rule
);

CREATE INDEX IF NOT EXISTS idx_txn_date ON transactions(date);
CREATE INDEX IF NOT EXISTS idx_txn_rule ON transactions(rule_id);

CREATE TABLE IF NOT EXISTS recurring_rules(
  id INTEGER PRIMARY KEY,
  start_date TEXT NOT NULL,         -- first occurrence
  amount_cents INTEGER NOT NULL,
  note TEXT DEFAULT '',
  every_n INTEGER NOT NULL,         -- repeat every N ...
  unit TEXT NOT NULL,               -- ... 'day', 'week' or 'month'
  last_generated_date TEXT,         -- occurrences exist up to this date
  end_date TEXT                     -- last allowed date (NULL = forever)
);

CREATE TABLE IF NOT EXISTS settings(
  key TEXT PRIMARY KEY,
  value TEXT NOT NULL
);
"""

DEFAULT_SETTINGS = {
    "currency": "$",
    "low_balance_cents": "10000",   # warn when a day's balance drops below $100
    "week_start": "sunday",         # 'sunday' or 'monday'
    "theme": "system",              # 'system', 'light' or 'dark'
}

UNITS = ("day", "week", "month")

_conn = None


# ---------------------------------------------------------------------------
# Connection management
# ---------------------------------------------------------------------------
def init(db_path) -> None:
    """Open (or create) the database file and bring the schema up to date."""
    global _conn
    close()
    _conn = sqlite3.connect(str(db_path))
    _conn.row_factory = sqlite3.Row
    _conn.execute("PRAGMA journal_mode = WAL")
    _conn.execute("PRAGMA synchronous = NORMAL")
    _conn.execute("PRAGMA busy_timeout = 3000")
    _migrate()


def close() -> None:
    global _conn
    if _conn is not None:
        _conn.close()
        _conn = None


def conn() -> sqlite3.Connection:
    if _conn is None:
        raise RuntimeError("database.init() has not been called")
    return _conn


def _migrate() -> None:
    c = conn()
    with c:
        c.executescript(SCHEMA)
        rule_cols = {r["name"] for r in c.execute("PRAGMA table_info('recurring_rules')")}
        if "end_date" not in rule_cols:
            c.execute("ALTER TABLE recurring_rules ADD COLUMN end_date TEXT")
        # Safety net: a rule can never create the same occurrence twice.
        c.execute(
            "CREATE UNIQUE INDEX IF NOT EXISTS ux_txn_unique "
            "ON transactions(date, amount_cents, note, rule_id)"
        )


# ---------------------------------------------------------------------------
# Settings
# ---------------------------------------------------------------------------
def get_setting(key: str) -> str:
    row = conn().execute("SELECT value FROM settings WHERE key=?", (key,)).fetchone()
    if row is None:
        return DEFAULT_SETTINGS.get(key, "")
    return row["value"]


def set_setting(key: str, value) -> None:
    c = conn()
    with c:
        c.execute(
            "INSERT INTO settings(key, value) VALUES(?, ?) "
            "ON CONFLICT(key) DO UPDATE SET value=excluded.value",
            (key, str(value)),
        )


# ---------------------------------------------------------------------------
# Transactions
# ---------------------------------------------------------------------------
_TXN_SELECT = (
    "SELECT t.id, t.date, t.amount_cents, t.note, t.rule_id, "
    "       r.every_n, r.unit "
    "FROM transactions t LEFT JOIN recurring_rules r ON r.id = t.rule_id "
)


def insert_txn(date_iso: str, cents: int, note: str = "") -> int:
    """Insert a one-off transaction and return its id."""
    c = conn()
    with c:
        cur = c.execute(
            "INSERT INTO transactions(date, amount_cents, note, rule_id) VALUES (?,?,?,NULL)",
            (date_iso, cents, note),
        )
        return cur.lastrowid


def update_txn(txn_id: int, date_iso: str, cents: int, note: str = "") -> None:
    """Change a single transaction (also used for one recurring occurrence)."""
    c = conn()
    with c:
        c.execute(
            "UPDATE transactions SET date=?, amount_cents=?, note=? WHERE id=?",
            (date_iso, cents, note, txn_id),
        )


def delete_txn(txn_id: int) -> None:
    c = conn()
    with c:
        c.execute("DELETE FROM transactions WHERE id=?", (txn_id,))


def get_txn(txn_id: int):
    """One transaction, including the interval of its rule (if any)."""
    return conn().execute(_TXN_SELECT + "WHERE t.id=?", (txn_id,)).fetchone()


def list_by_date(day_iso: str):
    """All transactions on one day: income first, then the largest expenses."""
    return conn().execute(
        _TXN_SELECT + "WHERE t.date=? ORDER BY t.amount_cents DESC, t.id",
        (day_iso,),
    ).fetchall()


def balance_on_or_before(day_iso: str) -> int:
    """Ending balance of a day = sum of every transaction up to and including it."""
    row = conn().execute(
        "SELECT COALESCE(SUM(amount_cents), 0) FROM transactions WHERE date <= ?",
        (day_iso,),
    ).fetchone()
    return row[0]


def daily_balances(first_iso: str, last_iso: str) -> dict:
    """Return {iso_date: ending_balance_cents} for every day in [first, last]."""
    c = conn()
    first = date.fromisoformat(first_iso)
    last = date.fromisoformat(last_iso)
    running = c.execute(
        "SELECT COALESCE(SUM(amount_cents), 0) FROM transactions WHERE date < ?",
        (first_iso,),
    ).fetchone()[0]
    totals = {
        r["date"]: r["total"]
        for r in c.execute(
            "SELECT date, SUM(amount_cents) AS total FROM transactions "
            "WHERE date BETWEEN ? AND ? GROUP BY date",
            (first_iso, last_iso),
        )
    }
    out = {}
    d = first
    while d <= last:
        iso = d.isoformat()
        running += totals.get(iso, 0)
        out[iso] = running
        d += timedelta(days=1)
    return out


def period_totals(first_iso: str, last_iso: str):
    """Return (income_cents, expense_cents) for [first, last]; expense is <= 0."""
    row = conn().execute(
        "SELECT "
        " COALESCE(SUM(CASE WHEN amount_cents > 0 THEN amount_cents END), 0), "
        " COALESCE(SUM(CASE WHEN amount_cents < 0 THEN amount_cents END), 0) "
        "FROM transactions WHERE date BETWEEN ? AND ?",
        (first_iso, last_iso),
    ).fetchone()
    return row[0], row[1]


def adjust_balance(day_iso: str, target_cents: int, note: str = "Balance adjustment") -> int:
    """
    Make the balance on `day_iso` equal `target_cents` by adding one correcting
    transaction. Returns the amount that was added (0 if nothing changed).
    """
    diff = target_cents - balance_on_or_before(day_iso)
    if diff:
        insert_txn(day_iso, diff, note)
    return diff


# ---------------------------------------------------------------------------
# Recurring rules
# ---------------------------------------------------------------------------
def _add_months(d: date, months: int) -> date:
    """Add months to a date, clamping the day (Jan 31 + 1 month = Feb 28/29)."""
    idx = d.year * 12 + (d.month - 1) + months
    y, m = divmod(idx, 12)
    m += 1
    if m == 12:
        days_in_month = 31
    else:
        days_in_month = (date(y, m + 1, 1) - timedelta(days=1)).day
    return date(y, m, min(d.day, days_in_month))


def nth_occurrence(start: date, every_n: int, unit: str, k: int) -> date:
    """
    Date of occurrence number k (k=0 is the start date).

    Computed from the start date every time, so monthly rules never drift:
    a rule starting on Jan 31 gives Feb 28, Mar 31, Apr 30, ...
    """
    if unit == "day":
        return start + timedelta(days=every_n * k)
    if unit == "week":
        return start + timedelta(weeks=every_n * k)
    if unit == "month":
        return _add_months(start, every_n * k)
    raise ValueError(f"invalid unit: {unit!r}")


def occurrences_between(start: date, every_n: int, unit: str, after: date, until: date):
    """All occurrence dates d with after < d <= until (and d >= start)."""
    if until < start or until <= after:
        return []
    if after < start:
        k = 0
    elif unit == "month":
        months = (after.year - start.year) * 12 + (after.month - start.month)
        k = max(0, months // every_n - 1)
    else:
        step = every_n * (7 if unit == "week" else 1)
        k = max(0, (after - start).days // step - 1)
    out = []
    while True:
        d = nth_occurrence(start, every_n, unit, k)
        if d > until:
            return out
        if d > after:
            out.append(d)
        k += 1


def create_rule(start_iso: str, cents: int, note: str, every_n: int, unit: str,
                generate_until_iso: str = None) -> int:
    """Create a recurring rule (optionally generating occurrences) and return its id."""
    if unit not in UNITS:
        raise ValueError(f"invalid unit: {unit!r}")
    if every_n < 1:
        raise ValueError("every_n must be >= 1")
    c = conn()
    with c:
        cur = c.execute(
            "INSERT INTO recurring_rules(start_date, amount_cents, note, every_n, unit, "
            "last_generated_date, end_date) VALUES (?,?,?,?,?,NULL,NULL)",
            (start_iso, cents, note, every_n, unit),
        )
        rule_id = cur.lastrowid
    if generate_until_iso:
        generate_until(rule_id, generate_until_iso)
    return rule_id


def get_rule(rule_id: int):
    return conn().execute("SELECT * FROM recurring_rules WHERE id=?", (rule_id,)).fetchone()


def rules_all():
    return conn().execute("SELECT * FROM recurring_rules ORDER BY id").fetchall()


def generate_until(rule_id: int, until_iso: str) -> int:
    """
    Create the rule's occurrences up to `until_iso` (never past its end_date).
    Only dates after last_generated_date are created, so an occurrence the
    user deleted or edited is never re-created. Returns the number inserted.
    """
    c = conn()
    r = get_rule(rule_id)
    if r is None:
        return 0
    start = date.fromisoformat(r["start_date"])
    until = date.fromisoformat(until_iso)
    if r["end_date"]:
        until = min(until, date.fromisoformat(r["end_date"]))
    if r["last_generated_date"]:
        after = date.fromisoformat(r["last_generated_date"])
    else:
        after = start - timedelta(days=1)
    if until <= after:
        return 0

    dates = occurrences_between(start, r["every_n"], r["unit"], after, until)
    with c:
        c.executemany(
            "INSERT OR IGNORE INTO transactions(date, amount_cents, note, rule_id) "
            "VALUES (?,?,?,?)",
            [(d.isoformat(), r["amount_cents"], r["note"], rule_id) for d in dates],
        )
        c.execute(
            "UPDATE recurring_rules SET last_generated_date=? WHERE id=?",
            (until.isoformat(), rule_id),
        )
    return len(dates)


def generate_all_until(until_iso: str) -> None:
    for r in rules_all():
        generate_until(r["id"], until_iso)


def delete_rule(rule_id: int) -> None:
    """Delete a recurring rule and every one of its occurrences."""
    c = conn()
    with c:
        c.execute("DELETE FROM transactions WHERE rule_id=?", (rule_id,))
        c.execute("DELETE FROM recurring_rules WHERE id=?", (rule_id,))


def end_rule_before(rule_id: int, from_iso: str) -> None:
    """
    Stop a rule so its last occurrence is before `from_iso`, deleting the
    occurrences on/after that date ("delete this and future occurrences").
    If nothing would be left, the whole rule is removed.
    """
    r = get_rule(rule_id)
    if r is None:
        return
    if from_iso <= r["start_date"]:
        delete_rule(rule_id)
        return
    end_iso = (date.fromisoformat(from_iso) - timedelta(days=1)).isoformat()
    c = conn()
    with c:
        c.execute(
            "DELETE FROM transactions WHERE rule_id=? AND date >= ?", (rule_id, from_iso)
        )
        c.execute("UPDATE recurring_rules SET end_date=? WHERE id=?", (end_iso, rule_id))


def replace_rule_from(rule_id: int, from_iso: str, new_start_iso: str, cents: int,
                      note: str, every_n: int, unit: str, generate_until_iso: str) -> int:
    """
    "Edit this and future occurrences": end the old rule before `from_iso` and
    continue with a new rule that starts on `new_start_iso`. Returns the new id.
    If the new start is earlier than the edited occurrence, the old rule is
    ended before the new start instead, so the two never overlap.
    """
    end_rule_before(rule_id, min(from_iso, new_start_iso))
    return create_rule(new_start_iso, cents, note, every_n, unit, generate_until_iso)
