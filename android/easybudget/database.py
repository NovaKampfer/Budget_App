# easybudget/database.py
#
# The **data layer** of the Android app. Everything that touches the SQLite
# database lives here, so the UI code never writes SQL directly.
#
# The database stores:
#   1. accounts          - "profiles": separate budgets (e.g. Personal, Work),
#                          each with its own transactions and balance
#   2. transactions      - every expense (negative) or income (positive)
#   3. recurring_rules   - "recipes" that generate transactions, e.g.
#                          "$25 every day" or "$1,200 every month"
#   4. settings          - small key/value preferences (currency, theme, ...)
#
# Everything that reads or adds transactions works on the *current* profile
# (see set_current_account), so the UI never has to pass it around.
#
# Money is always stored as integer **cents** so rounding errors can never
# corrupt a balance ($12.34 is stored as 1234).
#
# The transactions / recurring_rules tables use the same layout as the
# Windows version, plus a few extra columns: account_id (which profile a row
# belongs to) and recurring_rules.end_date (for "delete this and future").

import sqlite3
from datetime import date, timedelta

SCHEMA = """
CREATE TABLE IF NOT EXISTS transactions(
  id INTEGER PRIMARY KEY,
  date TEXT NOT NULL,               -- YYYY-MM-DD
  amount_cents INTEGER NOT NULL,    -- negative = expense, positive = income
  note TEXT DEFAULT '',
  rule_id INTEGER,                  -- set when generated by a recurring rule
  account_id INTEGER NOT NULL DEFAULT 1
);

CREATE INDEX IF NOT EXISTS idx_txn_date ON transactions(date);
CREATE INDEX IF NOT EXISTS idx_txn_rule ON transactions(rule_id);

CREATE TABLE IF NOT EXISTS recurring_rules(
  id INTEGER PRIMARY KEY,
  start_date TEXT NOT NULL,         -- first occurrence
  amount_cents INTEGER NOT NULL,
  note TEXT DEFAULT '',
  every_n INTEGER NOT NULL,         -- repeat every N ...
  unit TEXT NOT NULL,               -- ... 'day', 'week' or 'month'
  last_generated_date TEXT,         -- occurrences exist up to this date
  end_date TEXT,                    -- last allowed date (NULL = forever)
  account_id INTEGER NOT NULL DEFAULT 1
);

CREATE TABLE IF NOT EXISTS accounts(
  id INTEGER PRIMARY KEY,
  name TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS settings(
  key TEXT PRIMARY KEY,
  value TEXT NOT NULL
);
"""

DEFAULT_SETTINGS = {
    "currency": "$",
    "low_balance_cents": "10000",   # warn when a day's balance drops below $100
    "week_start": "sunday",         # 'sunday' or 'monday'
    "theme": "system",              # 'system', 'light' or 'dark'
}

UNITS = ("day", "week", "month")
DEFAULT_ACCOUNT_NAME = "Personal"
MAX_ACCOUNT_NAME = 30

_conn = None
_account_id = 1      # the profile everything currently reads from / writes to


# ---------------------------------------------------------------------------
# Connection management
# ---------------------------------------------------------------------------
def init(db_path) -> None:
    """Open (or create) the database file and bring the schema up to date."""
    global _conn
    close()
    _conn = sqlite3.connect(str(db_path))
    _conn.row_factory = sqlite3.Row
    _conn.execute("PRAGMA journal_mode = WAL")
    _conn.execute("PRAGMA synchronous = NORMAL")
    _conn.execute("PRAGMA busy_timeout = 3000")
    _migrate()
    _load_current_account()


def close() -> None:
    global _conn
    if _conn is not None:
        _conn.close()
        _conn = None


def conn() -> sqlite3.Connection:
    if _conn is None:
        raise RuntimeError("database.init() has not been called")
    return _conn


def _migrate() -> None:
    c = conn()
    with c:
        c.executescript(SCHEMA)
        rule_cols = {r["name"] for r in c.execute("PRAGMA table_info('recurring_rules')")}
        if "end_date" not in rule_cols:
            c.execute("ALTER TABLE recurring_rules ADD COLUMN end_date TEXT")
        # Profiles were added in version 1.1: older data becomes profile 1.
        for table in ("transactions", "recurring_rules"):
            cols = {r["name"] for r in c.execute(f"PRAGMA table_info('{table}')")}
            if "account_id" not in cols:
                c.execute(f"ALTER TABLE {table} ADD COLUMN account_id INTEGER NOT NULL DEFAULT 1")
        c.execute("CREATE INDEX IF NOT EXISTS idx_txn_account_date "
                  "ON transactions(account_id, date)")
        if c.execute("SELECT COUNT(*) FROM accounts").fetchone()[0] == 0:
            c.execute("INSERT INTO accounts(id, name) VALUES (1, ?)", (DEFAULT_ACCOUNT_NAME,))
        # Safety net: a rule can never create the same occurrence twice.
        c.execute(
            "CREATE UNIQUE INDEX IF NOT EXISTS ux_txn_unique "
            "ON transactions(date, amount_cents, note, rule_id)"
        )


# ---------------------------------------------------------------------------
# Profiles (accounts)
# ---------------------------------------------------------------------------
def _load_current_account() -> None:
    global _account_id
    saved = get_setting("current_account")
    ids = [a["id"] for a in list_accounts()]
    _account_id = int(saved) if saved.isdigit() and int(saved) in ids else ids[0]


def list_accounts():
    return conn().execute("SELECT id, name FROM accounts ORDER BY id").fetchall()


def get_account(account_id: int):
    return conn().execute("SELECT id, name FROM accounts WHERE id=?", (account_id,)).fetchone()


def current_account() -> int:
    return _account_id


def set_current_account(account_id: int) -> None:
    global _account_id
    if get_account(account_id) is None:
        raise ValueError("That profile doesn't exist")
    _account_id = account_id
    set_setting("current_account", account_id)


def _clean_account_name(name: str, ignore_id=None) -> str:
    name = " ".join((name or "").split())
    if not name:
        raise ValueError("Enter a name")
    if len(name) > MAX_ACCOUNT_NAME:
        raise ValueError(f"Keep the name under {MAX_ACCOUNT_NAME} characters")
    for a in list_accounts():
        if a["name"].lower() == name.lower() and a["id"] != ignore_id:
            raise ValueError("A profile with that name already exists")
    return name


def create_account(name: str) -> int:
    name = _clean_account_name(name)
    c = conn()
    with c:
        return c.execute("INSERT INTO accounts(name) VALUES (?)", (name,)).lastrowid


def rename_account(account_id: int, name: str) -> None:
    name = _clean_account_name(name, ignore_id=account_id)
    c = conn()
    with c:
        c.execute("UPDATE accounts SET name=? WHERE id=?", (name, account_id))


def delete_account(account_id: int) -> None:
    """Delete a profile with all its data. The last profile can't be deleted."""
    accounts = list_accounts()
    if len(accounts) <= 1:
        raise ValueError("You need at least one profile")
    c = conn()
    with c:
        c.execute("DELETE FROM transactions WHERE account_id=?", (account_id,))
        c.execute("DELETE FROM recurring_rules WHERE account_id=?", (account_id,))
        c.execute("DELETE FROM accounts WHERE id=?", (account_id,))
    if account_id == _account_id:
        set_current_account(next(a["id"] for a in accounts if a["id"] != account_id))


# ---------------------------------------------------------------------------
# Settings
# ---------------------------------------------------------------------------
def get_setting(key: str) -> str:
    row = conn().execute("SELECT value FROM settings WHERE key=?", (key,)).fetchone()
    if row is None:
        return DEFAULT_SETTINGS.get(key, "")
    return row["value"]


def set_setting(key: str, value) -> None:
    c = conn()
    with c:
        c.execute(
            "INSERT INTO settings(key, value) VALUES(?, ?) "
            "ON CONFLICT(key) DO UPDATE SET value=excluded.value",
            (key, str(value)),
        )


# ---------------------------------------------------------------------------
# Transactions
# ---------------------------------------------------------------------------
_TXN_SELECT = (
    "SELECT t.id, t.date, t.amount_cents, t.note, t.rule_id, "
    "       r.every_n, r.unit "
    "FROM transactions t LEFT JOIN recurring_rules r ON r.id = t.rule_id "
)


def insert_txn(date_iso: str, cents: int, note: str = "") -> int:
    """Insert a one-off transaction into the current profile and return its id."""
    c = conn()
    with c:
        cur = c.execute(
            "INSERT INTO transactions(date, amount_cents, note, rule_id, account_id) "
            "VALUES (?,?,?,NULL,?)",
            (date_iso, cents, note, _account_id),
        )
        return cur.lastrowid


def update_txn(txn_id: int, date_iso: str, cents: int, note: str = "") -> None:
    """Change a single transaction (also used for one recurring occurrence)."""
    c = conn()
    with c:
        c.execute(
            "UPDATE transactions SET date=?, amount_cents=?, note=? WHERE id=?",
            (date_iso, cents, note, txn_id),
        )


def delete_txn(txn_id: int) -> None:
    c = conn()
    with c:
        c.execute("DELETE FROM transactions WHERE id=?", (txn_id,))


def get_txn(txn_id: int):
    """One transaction, including the interval of its rule (if any)."""
    return conn().execute(_TXN_SELECT + "WHERE t.id=?", (txn_id,)).fetchone()


def list_by_date(day_iso: str):
    """All transactions on one day: income first, then the largest expenses."""
    return conn().execute(
        _TXN_SELECT + "WHERE t.date=? AND t.account_id=? ORDER BY t.amount_cents DESC, t.id",
        (day_iso, _account_id),
    ).fetchall()


def balance_on_or_before(day_iso: str, account_id: int = None) -> int:
    """Ending balance of a day = sum of every transaction up to and including it."""
    row = conn().execute(
        "SELECT COALESCE(SUM(amount_cents), 0) FROM transactions "
        "WHERE date <= ? AND account_id = ?",
        (day_iso, _account_id if account_id is None else account_id),
    ).fetchone()
    return row[0]


def daily_balances(first_iso: str, last_iso: str) -> dict:
    """Return {iso_date: ending_balance_cents} for every day in [first, last]."""
    c = conn()
    first = date.fromisoformat(first_iso)
    last = date.fromisoformat(last_iso)
    running = c.execute(
        "SELECT COALESCE(SUM(amount_cents), 0) FROM transactions "
        "WHERE date < ? AND account_id = ?",
        (first_iso, _account_id),
    ).fetchone()[0]
    totals = {
        r["date"]: r["total"]
        for r in c.execute(
            "SELECT date, SUM(amount_cents) AS total FROM transactions "
            "WHERE date BETWEEN ? AND ? AND account_id = ? GROUP BY date",
            (first_iso, last_iso, _account_id),
        )
    }
    out = {}
    d = first
    while d <= last:
        iso = d.isoformat()
        running += totals.get(iso, 0)
        out[iso] = running
        d += timedelta(days=1)
    return out


def period_totals(first_iso: str, last_iso: str):
    """Return (income_cents, expense_cents) for [first, last]; expense is <= 0."""
    row = conn().execute(
        "SELECT "
        " COALESCE(SUM(CASE WHEN amount_cents > 0 THEN amount_cents END), 0), "
        " COALESCE(SUM(CASE WHEN amount_cents < 0 THEN amount_cents END), 0) "
        "FROM transactions WHERE date BETWEEN ? AND ? AND account_id = ?",
        (first_iso, last_iso, _account_id),
    ).fetchone()
    return row[0], row[1]


def adjust_balance(day_iso: str, target_cents: int, note: str = "Balance adjustment") -> int:
    """
    Make the balance on `day_iso` equal `target_cents` by adding one correcting
    transaction. Returns the amount that was added (0 if nothing changed).
    """
    diff = target_cents - balance_on_or_before(day_iso)
    if diff:
        insert_txn(day_iso, diff, note)
    return diff


# ---------------------------------------------------------------------------
# Recurring rules
# ---------------------------------------------------------------------------
def _add_months(d: date, months: int) -> date:
    """Add months to a date, clamping the day (Jan 31 + 1 month = Feb 28/29)."""
    idx = d.year * 12 + (d.month - 1) + months
    y, m = divmod(idx, 12)
    m += 1
    if m == 12:
        days_in_month = 31
    else:
        days_in_month = (date(y, m + 1, 1) - timedelta(days=1)).day
    return date(y, m, min(d.day, days_in_month))


def nth_occurrence(start: date, every_n: int, unit: str, k: int) -> date:
    """
    Date of occurrence number k (k=0 is the start date).

    Computed from the start date every time, so monthly rules never drift:
    a rule starting on Jan 31 gives Feb 28, Mar 31, Apr 30, ...
    """
    if unit == "day":
        return start + timedelta(days=every_n * k)
    if unit == "week":
        return start + timedelta(weeks=every_n * k)
    if unit == "month":
        return _add_months(start, every_n * k)
    raise ValueError(f"invalid unit: {unit!r}")


def occurrences_between(start: date, every_n: int, unit: str, after: date, until: date):
    """All occurrence dates d with after < d <= until (and d >= start)."""
    if until < start or until <= after:
        return []
    if after < start:
        k = 0
    elif unit == "month":
        months = (after.year - start.year) * 12 + (after.month - start.month)
        k = max(0, months // every_n - 1)
    else:
        step = every_n * (7 if unit == "week" else 1)
        k = max(0, (after - start).days // step - 1)
    out = []
    while True:
        d = nth_occurrence(start, every_n, unit, k)
        if d > until:
            return out
        if d > after:
            out.append(d)
        k += 1


def create_rule(start_iso: str, cents: int, note: str, every_n: int, unit: str,
                generate_until_iso: str = None, account_id: int = None) -> int:
    """Create a recurring rule (optionally generating occurrences) and return its id.
    It belongs to the current profile unless account_id is given."""
    if unit not in UNITS:
        raise ValueError(f"invalid unit: {unit!r}")
    if every_n < 1:
        raise ValueError("every_n must be >= 1")
    c = conn()
    with c:
        cur = c.execute(
            "INSERT INTO recurring_rules(start_date, amount_cents, note, every_n, unit, "
            "last_generated_date, end_date, account_id) VALUES (?,?,?,?,?,NULL,NULL,?)",
            (start_iso, cents, note, every_n, unit,
             _account_id if account_id is None else account_id),
        )
        rule_id = cur.lastrowid
    if generate_until_iso:
        generate_until(rule_id, generate_until_iso)
    return rule_id


def get_rule(rule_id: int):
    return conn().execute("SELECT * FROM recurring_rules WHERE id=?", (rule_id,)).fetchone()


def rules_all():
    return conn().execute("SELECT * FROM recurring_rules ORDER BY id").fetchall()


def generate_until(rule_id: int, until_iso: str) -> int:
    """
    Create the rule's occurrences up to `until_iso` (never past its end_date).
    Only dates after last_generated_date are created, so an occurrence the
    user deleted or edited is never re-created. Returns the number inserted.
    """
    c = conn()
    r = get_rule(rule_id)
    if r is None:
        return 0
    start = date.fromisoformat(r["start_date"])
    until = date.fromisoformat(until_iso)
    if r["end_date"]:
        until = min(until, date.fromisoformat(r["end_date"]))
    if r["last_generated_date"]:
        after = date.fromisoformat(r["last_generated_date"])
    else:
        after = start - timedelta(days=1)
    if until <= after:
        return 0

    dates = occurrences_between(start, r["every_n"], r["unit"], after, until)
    with c:
        c.executemany(
            "INSERT OR IGNORE INTO transactions(date, amount_cents, note, rule_id, account_id) "
            "VALUES (?,?,?,?,?)",
            [(d.isoformat(), r["amount_cents"], r["note"], rule_id, r["account_id"])
             for d in dates],
        )
        c.execute(
            "UPDATE recurring_rules SET last_generated_date=? WHERE id=?",
            (until.isoformat(), rule_id),
        )
    return len(dates)


def generate_all_until(until_iso: str) -> None:
    for r in rules_all():
        generate_until(r["id"], until_iso)


def delete_rule(rule_id: int) -> None:
    """Delete a recurring rule and every one of its occurrences."""
    c = conn()
    with c:
        c.execute("DELETE FROM transactions WHERE rule_id=?", (rule_id,))
        c.execute("DELETE FROM recurring_rules WHERE id=?", (rule_id,))


def end_rule_before(rule_id: int, from_iso: str) -> None:
    """
    Stop a rule so its last occurrence is before `from_iso`, deleting the
    occurrences on/after that date ("delete this and future occurrences").
    If nothing would be left, the whole rule is removed.
    """
    r = get_rule(rule_id)
    if r is None:
        return
    if from_iso <= r["start_date"]:
        delete_rule(rule_id)
        return
    end_iso = (date.fromisoformat(from_iso) - timedelta(days=1)).isoformat()
    c = conn()
    with c:
        c.execute(
            "DELETE FROM transactions WHERE rule_id=? AND date >= ?", (rule_id, from_iso)
        )
        c.execute("UPDATE recurring_rules SET end_date=? WHERE id=?", (end_iso, rule_id))


def replace_rule_from(rule_id: int, from_iso: str, new_start_iso: str, cents: int,
                      note: str, every_n: int, unit: str, generate_until_iso: str) -> int:
    """
    "Edit this and future occurrences": end the old rule before `from_iso` and
    continue with a new rule that starts on `new_start_iso`. Returns the new id.
    If the new start is earlier than the edited occurrence, the old rule is
    ended before the new start instead, so the two never overlap.
    """
    rule = get_rule(rule_id)
    account_id = rule["account_id"] if rule is not None else None
    end_rule_before(rule_id, min(from_iso, new_start_iso))
    return create_rule(new_start_iso, cents, note, every_n, unit, generate_until_iso,
                       account_id=account_id)


# ---------------------------------------------------------------------------
# Backup: export everything to a plain dict (saved as JSON) and restore it
# ---------------------------------------------------------------------------
BACKUP_APP = "EasyBudget"
BACKUP_FORMAT = 1

_RULE_COLS = ("id", "start_date", "amount_cents", "note", "every_n", "unit",
              "last_generated_date", "end_date", "account_id")
_TXN_COLS = ("id", "date", "amount_cents", "note", "rule_id", "account_id")


def export_data() -> dict:
    """Every profile, transaction, recurring rule and setting."""
    from datetime import datetime

    c = conn()
    return {
        "app": BACKUP_APP,
        "format": BACKUP_FORMAT,
        "exported_at": datetime.now().isoformat(timespec="seconds"),
        "settings": {r["key"]: r["value"] for r in c.execute("SELECT key, value FROM settings")},
        "accounts": [dict(r) for r in c.execute("SELECT id, name FROM accounts ORDER BY id")],
        "recurring_rules": [dict(r) for r in c.execute(
            f"SELECT {', '.join(_RULE_COLS)} FROM recurring_rules ORDER BY id")],
        "transactions": [dict(r) for r in c.execute(
            f"SELECT {', '.join(_TXN_COLS)} FROM transactions ORDER BY id")],
    }


def _check_date(value, what, allow_none=False):
    if value is None and allow_none:
        return
    try:
        date.fromisoformat(value)
    except (TypeError, ValueError):
        raise ValueError(f"The backup has an invalid {what}") from None


def validate_backup(data) -> None:
    """Raise ValueError with a readable message if `data` isn't a usable backup."""
    if not isinstance(data, dict) or data.get("app") != BACKUP_APP:
        raise ValueError("This file isn't an EasyBudget backup")
    fmt = data.get("format")
    if not isinstance(fmt, int) or fmt > BACKUP_FORMAT:
        raise ValueError("This backup was made by a newer version of the app")
    for key in ("settings", "accounts", "recurring_rules", "transactions"):
        if not isinstance(data.get(key), dict if key == "settings" else list):
            raise ValueError("The backup file is incomplete")
    accounts = data["accounts"]
    if not accounts:
        raise ValueError("The backup has no profiles")
    account_ids = set()
    for a in accounts:
        if not isinstance(a, dict) or not isinstance(a.get("id"), int) \
                or not isinstance(a.get("name"), str) or not a["name"].strip():
            raise ValueError("The backup has an invalid profile")
        account_ids.add(a["id"])
    rule_ids = set()
    for r in data["recurring_rules"]:
        if not isinstance(r, dict) or any(k not in r for k in _RULE_COLS):
            raise ValueError("The backup has an invalid recurring entry")
        if not all(isinstance(r[k], int) for k in ("id", "amount_cents", "every_n", "account_id")) \
                or r["unit"] not in UNITS or r["every_n"] < 1 or r["account_id"] not in account_ids:
            raise ValueError("The backup has an invalid recurring entry")
        _check_date(r["start_date"], "recurring entry date")
        _check_date(r["last_generated_date"], "recurring entry date", allow_none=True)
        _check_date(r["end_date"], "recurring entry date", allow_none=True)
        rule_ids.add(r["id"])
    for t in data["transactions"]:
        if not isinstance(t, dict) or any(k not in t for k in _TXN_COLS):
            raise ValueError("The backup has an invalid transaction")
        if not isinstance(t["id"], int) or not isinstance(t["amount_cents"], int) \
                or t["account_id"] not in account_ids \
                or (t["rule_id"] is not None and t["rule_id"] not in rule_ids):
            raise ValueError("The backup has an invalid transaction")
        _check_date(t["date"], "transaction date")
    for key, value in data["settings"].items():
        if not isinstance(key, str) or not isinstance(value, str):
            raise ValueError("The backup has invalid settings")


def import_data(data: dict) -> None:
    """
    Replace ALL current data with the backup. Everything happens in one
    database transaction, so a bad file can never leave half-imported data.
    """
    validate_backup(data)
    c = conn()
    with c:
        for table in ("transactions", "recurring_rules", "accounts", "settings"):
            c.execute(f"DELETE FROM {table}")
        c.executemany("INSERT INTO accounts(id, name) VALUES (?, ?)",
                      [(a["id"], a["name"].strip()) for a in data["accounts"]])
        c.executemany(
            f"INSERT INTO recurring_rules({', '.join(_RULE_COLS)}) "
            f"VALUES ({', '.join('?' for _ in _RULE_COLS)})",
            [tuple(r[k] for k in _RULE_COLS) for r in data["recurring_rules"]])
        c.executemany(
            f"INSERT INTO transactions({', '.join(_TXN_COLS)}) "
            f"VALUES ({', '.join('?' for _ in _TXN_COLS)})",
            [tuple(t[k] if k != "note" else (t[k] or "") for k in _TXN_COLS)
             for t in data["transactions"]])
        c.executemany("INSERT INTO settings(key, value) VALUES (?, ?)",
                      list(data["settings"].items()))
    _load_current_account()


def describe_backup(data: dict) -> str:
    """e.g. '2 profiles · 418 transactions · saved Nov 9, 2026'"""
    n_acc, n_txn = len(data.get("accounts", [])), len(data.get("transactions", []))
    text = (f"{n_acc} profile{'s' if n_acc != 1 else ''} · "
            f"{n_txn} transaction{'s' if n_txn != 1 else ''}")
    try:
        from datetime import datetime

        saved = datetime.fromisoformat(data["exported_at"])
        text += f" · saved {saved:%b} {saved.day}, {saved.year}"
    except (KeyError, TypeError, ValueError):
        pass
    return text
